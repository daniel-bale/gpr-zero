#!/usr/bin/env python3
"""
Process divergent coverage article samples through LLM for neutral summarization.

This script reads the markdown files generated by the article sampling script,
processes them through PromptManager using the neutral summarization prompt,
and generates summaries for each week/newspaper combination.
"""

import pandas as pd
import polars as pl
from pathlib import Path
import re
import sys
from typing import Dict, List, Any
import json

# Add src to path for imports
sys.path.append('src')
from gpr_zero.llm.prompt_manager import PromptManager


def parse_markdown_file(filepath: Path) -> Dict[str, Any]:
    """Parse a markdown file to extract metadata, statistics, and article content"""
    
    content = filepath.read_text(encoding='utf-8')
    
    # Extract basic info from filename
    filename = filepath.stem
    parts = filename.split('_')
    week_date = parts[0]
    newspaper = '_'.join(parts[1:])
    
    # Extract summary statistics
    stats = {}
    
    # Extract week period
    week_match = re.search(r'\*\*Week Period\*\*: (.+)', content)
    if week_match:
        stats['week_period'] = week_match.group(1)
    
    # Extract total articles
    total_match = re.search(r'\*\*Total Articles\*\*: ([\d,]+)', content)
    if total_match:
        stats['total_articles'] = int(total_match.group(1).replace(',', ''))
    
    # Extract sampled articles
    sampled_match = re.search(r'\*\*Sampled Articles\*\*: ([\d,]+)', content)
    if sampled_match:
        stats['sampled_articles'] = int(sampled_match.group(1).replace(',', ''))
    
    # Extract GPR articles
    gpr_match = re.search(r'\*\*GPR Articles in Sample\*\*: ([\d,]+)', content)
    if gpr_match:
        stats['gpr_articles'] = int(gpr_match.group(1).replace(',', ''))
    
    # Extract GPR share
    share_match = re.search(r'\*\*GPR Share in Sample\*\*: ([\d.]+)%', content)
    if share_match:
        stats['gpr_share'] = float(share_match.group(1))
    
    # Extract category breakdown
    category_counts = {}
    category_section = re.search(r'## Category Breakdown \(from sample\)\n\n(.*?)\n\n---', content, re.DOTALL)
    if category_section:
        for line in category_section.group(1).split('\n'):
            if line.strip().startswith('- **'):
                # Parse: - **Military Escalation**: 31 articles (67.39% of sample)
                match = re.search(r'- \*\*(.+?)\*\*: ([\d,]+) articles', line)
                if match:
                    category = match.group(1)
                    count = int(match.group(2).replace(',', ''))
                    category_counts[category] = count
    
    # Extract article content for each category
    category_articles = {}
    
    # Split content by category sections
    category_sections = re.split(r'## (.+?) Articles \((\d+) samples\)', content)
    
    for i in range(1, len(category_sections), 3):
        if i + 2 < len(category_sections):
            category_name = category_sections[i]
            sample_count = int(category_sections[i + 1])
            section_content = category_sections[i + 2]
            
            # Extract individual articles
            articles = []
            article_sections = re.split(r'### Article \d+', section_content)
            
            for article_section in article_sections[1:]:  # Skip first empty section
                article_data = {}
                
                # Extract date
                date_match = re.search(r'\*\*Date\*\*: (.+)', article_section)
                if date_match:
                    article_data['date'] = date_match.group(1)
                
                # Extract title
                title_match = re.search(r'\*\*Title\*\*: (.+)', article_section)
                if title_match:
                    article_data['title'] = title_match.group(1)
                
                # Extract categories (for multi-category articles)
                categories_match = re.search(r'\*\*Categories\*\*: (.+)', article_section)
                if categories_match:
                    article_data['categories'] = categories_match.group(1)
                
                # Extract URL
                url_match = re.search(r'\*\*URL\*\*: (.+)', article_section)
                if url_match:
                    article_data['url'] = url_match.group(1)
                
                # Extract outlet
                outlet_match = re.search(r'\*\*Outlet\*\*: (.+)', article_section)
                if outlet_match:
                    article_data['outlet'] = outlet_match.group(1)
                
                # Extract content
                content_match = re.search(r'\*\*Content\*\*: (.+?)(?=\n\n---|\Z)', article_section, re.DOTALL)
                if content_match:
                    article_data['content'] = content_match.group(1).strip()
                
                if article_data:  # Only add if we extracted some data
                    articles.append(article_data)
            
            category_articles[category_name] = articles
    
    return {
        'week_date': week_date,
        'newspaper': newspaper,
        'filepath': str(filepath),
        'stats': stats,
        'category_counts': category_counts,
        'category_articles': category_articles
    }


def create_summarization_prompt(parsed_data: Dict[str, Any]) -> str:
    """Create a structured prompt for LLM summarization"""
    
    week_date = parsed_data['week_date']
    newspaper = parsed_data['newspaper']
    stats = parsed_data['stats']
    category_counts = parsed_data['category_counts']
    category_articles = parsed_data['category_articles']
    
    # Build the prompt content
    prompt_content = f"""# {newspaper} Coverage Analysis - Week of {week_date}

## Summary Statistics
- Total Articles: {stats.get('total_articles', 'N/A'):,}
- GPR Articles: {stats.get('gpr_articles', 'N/A'):,}
- GPR Share: {stats.get('gpr_share', 'N/A'):.2f}%

## Category Distribution
"""
    
    for category, count in category_counts.items():
        prompt_content += f"- {category}: {count} articles\n"
    
    prompt_content += "\n## Article Samples by Category\n\n"
    
    # Add article samples for each category
    for category, articles in category_articles.items():
        if articles:
            prompt_content += f"### {category} ({len(articles)} articles)\n\n"
            
            for i, article in enumerate(articles[:5], 1):  # Limit to first 5 articles per category
                prompt_content += f"**Article {i}:**\n"
                prompt_content += f"Title: {article.get('title', 'N/A')}\n"
                prompt_content += f"Date: {article.get('date', 'N/A')}\n"
                if 'categories' in article:
                    prompt_content += f"Categories: {article['categories']}\n"
                prompt_content += f"Content: {article.get('content', 'N/A')}\n\n"
    
    return prompt_content


def main():
    """Main function to process all markdown files through LLM"""
    
    # Initialize PromptManager
    print("Initializing PromptManager...")
    prompt_manager = PromptManager()
    
    # Get input directory
    input_dir = Path("data_analysis/output/divergent_coverage/article_samples")
    
    # Get all markdown files
    markdown_files = list(input_dir.glob("*.md"))
    print(f"Found {len(markdown_files)} markdown files to process")
    
    if not markdown_files:
        print("No markdown files found!")
        return
    
    # Create output directory
    output_dir = input_dir / "llm_summaries"
    output_dir.mkdir(exist_ok=True)
    
    # Process each file
    results = []
    
    for i, filepath in enumerate(markdown_files, 1):
        print(f"\n[{i}/{len(markdown_files)}] Processing {filepath.name}...")
        
        try:
            # Parse markdown file
            parsed_data = parse_markdown_file(filepath)
            
            # Create prompt content
            prompt_content = create_summarization_prompt(parsed_data)
            
            # Call LLM for summarization
            print(f"  Calling LLM for neutral summarization...")
            response = prompt_manager.call_llm_with_prompt_file(
                prompt_template_file="prompts/summarize_divergent_coverage.json",
                template_args_list=[{}, {"content": prompt_content}]  # Empty dict for system message, content for user message
            )
            summary = response["text"]
            
            # Save individual summary
            summary_filename = f"{parsed_data['week_date']}_{parsed_data['newspaper']}_summary.txt"
            summary_filepath = output_dir / summary_filename
            summary_filepath.write_text(summary, encoding='utf-8')
            
            print(f"  Saved summary: {summary_filepath}")
            
            # Collect results
            result = {
                'week_date': parsed_data['week_date'],
                'newspaper': parsed_data['newspaper'],
                'total_articles': parsed_data['stats'].get('total_articles', 0),
                'gpr_articles': parsed_data['stats'].get('gpr_articles', 0),
                'gpr_share': parsed_data['stats'].get('gpr_share', 0.0),
                'summary': summary,
                'summary_file': summary_filename
            }
            
            # Add category counts
            for category, count in parsed_data['category_counts'].items():
                result[f'count_{category.replace(" ", "_")}'] = count
            
            results.append(result)
            
        except Exception as e:
            print(f"  Error processing {filepath.name}: {e}")
            import traceback
            traceback.print_exc()
            continue
    
    # Save comprehensive results
    if results:
        # Create DataFrame
        results_df = pl.DataFrame(results)
        
        # Save as CSV
        csv_path = output_dir / "divergent_coverage_summaries.csv"
        results_df.write_csv(csv_path)
        print(f"\nSaved comprehensive results to: {csv_path}")
        
        # Print summary
        print(f"\nProcessed {len(results)} files successfully")
        print(f"Total GPR articles analyzed: {results_df['gpr_articles'].sum():,}")
        
        # Show results by newspaper
        by_newspaper = results_df.group_by("newspaper").agg([
            pl.count().alias("weeks"),
            pl.sum("gpr_articles").alias("total_gpr_articles"),
            pl.mean("gpr_share").alias("avg_gpr_share")
        ])
        print("\nBy newspaper:")
        print(by_newspaper)
        
    else:
        print("No files were successfully processed!")


if __name__ == "__main__":
    main()